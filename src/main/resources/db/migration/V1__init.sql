CREATE TABLE _wallet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,

    money BIGINT NOT NULL,

    wallet_type VARCHAR(50) NOT NULL
        CHECK (wallet_type IN ('USER', 'STORE', 'SYSTEM')),

    system_wallet_code VARCHAR(50) UNIQUE
        CHECK (system_wallet_code IN ('EXTERNAL', 'FEES')),

    allow_negative BOOLEAN NOT NULL,

    currency VARCHAR(50) NOT NULL
        CHECK (currency IN ('KZT')),

    constraint chk_wallet_balance CHECK (
        allow_negative OR money >= 0
    ),

    CONSTRAINT chk_wallet_rules CHECK (
        (
            wallet_type IN ('USER', 'STORE')
            AND system_wallet_code IS NULL
            AND allow_negative = FALSE
        )
        OR
        (
            wallet_type = 'SYSTEM'
            AND system_wallet_code = 'EXTERNAL'
            AND allow_negative = TRUE
        )
        OR
        (
            wallet_type = 'SYSTEM'
            AND system_wallet_code = 'FEES'
            AND allow_negative = FALSE
        )
    )
);

create table _user(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    name VARCHAR NOT NULL,
    surname varchar not null,
    phone varchar not null,
    wallet_id bigint references _wallet(id) UNIQUE
);

create table _store(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    name varchar not null,
    rating int CHECK (rating >= 0 AND rating <= 10) not null,
    phone varchar(13) not null,
    wallet_id bigint references _wallet(id) UNIQUE
);

create table _item(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    name varchar not null,
    article varchar not null,
    rating int not null check (rating >=0 and rating <= 10),
    amount int not null check (amount > 0),
    price bigint not null check (price > 0),
    store_id bigint references _store(id) not null
);

create table _transfer (
    created_at timestamp(6) with time zone not null,
    from_wallet bigint not null,
    id bigint generated by default as identity,
    money bigint not null check (money > 0),
    order_id bigint,
    to_wallet bigint not null check (from_wallet != to_wallet),
    updated_at timestamp(6) with time zone not null,
    currency varchar(255) not null check ((currency in ('KZT'))),
    transfer_status varchar(255) not null check ((transfer_status in ('PENDING','COMPLETED','FAILED'))),
    transfer_type varchar(255) not null check ((transfer_type in ('TOPUP','WITHDRAWAL','P2P','PAYMENT','REFUND'))),
    primary key (id),

    CONSTRAINT chk_order_id_status CHECK (
            (
                order_id is not null
                and transfer_type in ('PAYMENT', 'REFUND')
            )
            or
            (
                order_id is null
                and transfer_type in ('TOPUP','WITHDRAWAL','P2P')
            )
    )
);

create table _order (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        store_id bigint not null,
        total_amount bigint not null CHECK ( total_amount> 0),
        updated_at timestamp(6) with time zone not null,
        user_id bigint not null,
        order_status varchar(255) not null check ((order_status in ('CREATED','RESERVED','COMPLETED','CANCELLED','EXPIRED'))),
        primary key (id)
    );

create table _order_item (
